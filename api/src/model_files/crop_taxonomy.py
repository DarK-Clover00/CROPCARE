def get_crop_profile(crop_name):
    """
    Looks up botanical taxonomy profile for any of the 100 supported plant/crop varieties.
    Fuzzy-matches lowercase and aliases.
    """
    if not crop_name:
        return None

    norm = crop_name.strip().lower()
    for key, data in CROP_TAXONOMY_100.items():
        if key.lower() == norm or key.lower() in norm or norm in key.lower():
            return data

    # Default fallback
    return {
        "id": 0,
        "name": crop_name,
        "botanical_species": "Plantae",
        "family": "Angiosperms",
        "leaf_morphology": "Compound Foliar Lamina",
        "margin": "Entire",
        "venation": "Pinnate",
        "disease_supported": False,
        "supported_diseases": [],
        "category": "Agricultural Plant"
    }

